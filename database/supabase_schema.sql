-- LearnPath AI: PostgreSQL schema for Supabase.
-- Run in Supabase -> SQL Editor. Safe to re-run.
-- The backend (ddl-auto=update) also keeps tables in sync, and SeedData.java
-- fills subjects/concepts/lessons/questions on the first backend start.

create table if not exists subjects (
  id integer generated by default as identity primary key,
  name varchar(80) not null unique,
  description varchar(500)
);

create table if not exists concepts (
  id integer generated by default as identity primary key,
  subject_id integer not null,
  name varchar(100) not null,
  description varchar(1000),
  display_order integer not null
);

create table if not exists dependencies (
  id integer generated by default as identity primary key,
  prerequisite_concept_id integer not null,
  dependent_concept_id integer not null,
  unique (prerequisite_concept_id, dependent_concept_id)
);

create table if not exists lessons (
  id integer generated by default as identity primary key,
  concept_id integer not null,
  title varchar(160) not null,
  class_type varchar(30) not null,
  tagline varchar(200),
  content text not null,
  example_code text,
  unique (concept_id, class_type)
);

create table if not exists questions (
  id integer generated by default as identity primary key,
  concept_id integer not null,
  question_text varchar(1000) not null,
  option_a varchar(500) not null,
  option_b varchar(500) not null,
  option_c varchar(500) not null,
  option_d varchar(500) not null,
  correct_option varchar(1) not null,
  explanation varchar(1500)
);

create table if not exists students (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  email varchar(150) not null unique,
  password varchar(100) not null,
  role varchar(30) not null
);

create table if not exists concept_mastery (
  id integer generated by default as identity primary key,
  student_id integer not null,
  concept_id integer not null,
  mastery_score double precision not null,
  correct_answers integer not null,
  total_attempts integer not null,
  assigned_class_type varchar(30),
  updated_at timestamp(6) not null,
  unique (student_id, concept_id)
);

create table if not exists quiz_attempts (
  id integer generated by default as identity primary key,
  student_id integer not null,
  concept_id integer not null,
  question_id integer not null,
  selected_option varchar(1) not null,
  is_correct boolean not null,
  attempted_at timestamp(6) not null
);

create table if not exists quiz_sessions (
  id integer generated by default as identity primary key,
  student_id integer not null,
  subject_id integer not null,
  concept_id integer not null,
  total_questions integer not null,
  correct_answers integer not null,
  score_percent double precision not null,
  passed boolean not null,
  attempt_number integer not null,
  completed_at timestamp(6) not null
);

-- SECURITY: Supabase exposes the public schema through its REST API.
-- The backend connects directly with the database role (bypasses RLS), so turn
-- RLS on with no policies: the public API key then cannot read any table
-- (students.password included).
alter table subjects        enable row level security;
alter table concepts        enable row level security;
alter table dependencies    enable row level security;
alter table lessons         enable row level security;
alter table questions       enable row level security;
alter table students        enable row level security;
alter table concept_mastery enable row level security;
alter table quiz_attempts   enable row level security;
alter table quiz_sessions   enable row level security;
